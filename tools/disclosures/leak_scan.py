#!/usr/bin/env python3
"""Check the text of a disclosure for leaks before it goes out.

Checks the text that goes public or to third parties (issue, advisory, mail) for:

- ERROR    AI hints (Claude, Anthropic, Codex, OpenAI, GPT, Copilot, "generated by",
           Co-Authored-By ...), local paths and machine names, internal addresses,
           own fork/project names, credential patterns, customer names
- WARNING  soft terms (LLM, "AI", agent), exploit hints (PoC, payload,
           reverse shell), non-ASCII characters

Exceptions belong IN THE DRAFT (JSON field "leak_allow", list of terms), so that
they are hashed and approved together with the text - e.g. "Claude Code" when the
reported product itself is a Claude Code plugin.

Customer names and own machine, account and project names are NOT in a versioned
file (the repository is public) but in the shared deny list
private/public_check_denylist.txt (git-ignored, also used by tools/public_check.py),
plus optionally private/disclosures/leak_names.txt for extra entries: one entry per
line, literal or as 're:<regular expression>'.

    python tools/disclosures/leak_scan.py <draft.md>          # draft format
    python tools/disclosures/leak_scan.py --text <file.txt>   # any text
    python tools/disclosures/leak_scan.py --self-test

Exit: 0 clean (warnings at most), 1 error findings, 2 operator error.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common import DENYLIST, LEAK_NAMES, DisclosureError, err, out, read_draft  # noqa: E402

ERROR_PATTERNS = [
    ("AI hint", r"\bclaude\b"),
    ("AI hint", r"\banthropic\b"),
    ("AI hint", r"\bcodex\b"),
    ("AI hint", r"\bopenai\b"),
    ("AI hint", r"\bchat-?gpt\b|\bgpt-?\d"),
    ("AI hint", r"\bcopilot\b"),
    ("AI hint", r"\bgemini\b"),
    ("AI hint", r"\bsonnet\b|\bopus\b|\bhaiku\b"),
    ("AI hint", r"generated (?:with|by)"),
    ("AI hint", r"co-authored-by"),
    ("AI hint", r"\bclaudex\b"),
    ("local path", r"\b[a-z]:[\\/]"),
    ("local path", r"(?:^|[\s(`'\"])/(?:users|home|mnt/[a-z])/"),
    ("local path", r"\\\\[a-z0-9_.-]+\\"),
    ("local path", r"\bappdata\b|\bscratchpad\b|\.claudex-tmp\b|\bquarantaene\b|\bquarantine/"),
    ("own name", r"\bujc\b|-ujc\b|\bujc[-_]"),
    ("internal address", r"\b(?:10|127)\.\d{1,3}\.\d{1,3}\.\d{1,3}\b"),
    ("internal address", r"\b192\.168\.\d{1,3}\.\d{1,3}\b"),
    ("internal address", r"\b172\.(?:1[6-9]|2\d|3[01])\.\d{1,3}\.\d{1,3}\b"),
    ("credentials", r"\bgh[pousr]_[A-Za-z0-9]{20,}"),
    ("credentials", r"\bgithub_pat_[A-Za-z0-9_]{20,}"),
    ("credentials", r"\bsk-[A-Za-z0-9_-]{20,}"),
    ("credentials", r"\bAKIA[0-9A-Z]{16}\b"),
    ("credentials", r"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
    ("credentials", r"(?:password|passwd|pwd|secret|token|api_key)\s*[=:]\s*['\"]?[^\s'\"<>{}]{6,}"),
    ("credentials", r"bearer\s+[A-Za-z0-9._~+/-]{20,}"),
    ("credentials", r"\$\{vault:"),
]

WARN_PATTERNS = [
    ("soft AI term", r"\bllm\b|\bai\b|\bagentic\b|\bagents?\b"),
    ("exploit detail?", r"\bpoc\b|proof[- ]of[- ]concept|\bpayload\b|reverse shell|\bexploit\b"),
]

_NON_ASCII = re.compile(r"[^\x00-\x7f]")


def internal_names(paths=None):
    """Internal names from the shared deny list private/public_check_denylist.txt plus the
    optional extra list private/disclosures/leak_names.txt: one entry per line,
    're:<pattern>' for a regular expression, otherwise literal; '#' starts a comment line."""
    names = []
    if paths is None and not Path(DENYLIST).is_file():
        # fail closed: without the shared deny list no customer or internal name is checked at
        # all - an empty file is fine (a deliberate "none"), a missing one is not
        raise DisclosureError(f"deny list {Path(DENYLIST).name} missing under private/ - create it "
                              "(may be empty) before scanning outgoing text (docs/SETUP.md)")
    for path in (DENYLIST, LEAK_NAMES) if paths is None else paths:
        if Path(path).is_file():
            names += [z.strip() for z in Path(path).read_text(encoding="utf-8").splitlines()
                      if z.strip() and not z.lstrip().startswith("#")]
    return list(dict.fromkeys(names))


def scan(text: str, allowed=(), names=None):
    """List of (level, kind, line, match)."""
    # leak_allow comes from the draft: a plain string would be iterated per character and blank
    # out every one of its letters from the checked line - only a list of strings is accepted
    if isinstance(allowed, str) or not isinstance(allowed or [], (list, tuple)) \
            or not all(isinstance(a, str) for a in (allowed or [])):
        raise DisclosureError("leak_allow must be a list of strings")
    allowed = [a for a in (allowed or []) if a]
    names = internal_names() if names is None else names
    findings = []
    for nr, line in enumerate(text.splitlines(), 1):
        check_line = line
        for a in allowed:
            check_line = re.sub(re.escape(a), " " * len(a), check_line, flags=re.I)
        for level, patterns in (("ERROR", ERROR_PATTERNS), ("WARNING", WARN_PATTERNS)):
            for kind, pattern in patterns:
                for m in re.finditer(pattern, check_line, flags=re.I):
                    findings.append((level, kind, nr, m.group(0)[:60]))
        for name in names:
            # lookarounds instead of \b: a name ending in punctuation ("Firma GmbH.") has no
            # word boundary after it and would never match
            pattern = name[3:] if name.startswith("re:") else r"(?<!\w)" + re.escape(name) + r"(?!\w)"
            if re.search(pattern, check_line, flags=re.I):
                findings.append(("ERROR", "internal name", nr, "<internal name>"))
        if _NON_ASCII.search(line):
            findings.append(("WARNING", "non-ASCII", nr, repr(_NON_ASCII.search(line).group(0))))
    return findings


def report(findings) -> int:
    errors = [f for f in findings if f[0] == "ERROR"]
    for level, kind, nr, match in findings:
        # never print credentials in clear text on the console
        shown = "<redacted>" if kind == "credentials" else match
        out(f"{level}: line {nr}: {kind}: {shown}")
    out(f"leak_scan: {len(errors)} errors, {len(findings) - len(errors)} warnings")
    return 1 if errors else 0


def self_test() -> int:
    cases = [
        ("Found during an internal security review.", [], 0),
        ("Reported with Claude Code assistance.", [], 1),
        ("OMC v5.6.1, Windows 11, Claude Code.", ["Claude Code"], 0),
        ("see D:\\work\\x", [], 1),
        ("path /home/user/x", [], 1),
        ("fork some-tool-ujc", [], 1),
        ("host 192.168.1.10", [], 1),
        ("server nas-intern-7 down", [], 1),           # re: entry
        ("token=abcdefghijk", [], 1),
        ("ghp_" + "a" * 36, [], 1),
        ("Codex found this", [], 1),
        ("the agent removes the section", [], 0),   # warning only
        ("Generated with something", [], 1),
        ("plain text without issues", [], 0),
        ("Customer Musterfirma GmbH", [], 1),
    ]
    bad = 0
    for text, allowed, expected in cases:
        findings = scan(text, allowed, names=["Musterfirma", r"re:\bnas-intern-\d+\b"])
        actual = 1 if any(f[0] == "ERROR" for f in findings) else 0
        if actual != expected:
            bad += 1
            out(f"ERROR: self-test {text!r}: expected {expected}, got {actual}")
    total = len(cases)
    # shared deny list + optional extra list: both are read, comments skipped, missing file ok
    import tempfile
    with tempfile.TemporaryDirectory() as td:
        deny, extra = Path(td) / "public_check_denylist.txt", Path(td) / "leak_names.txt"
        deny.write_text("# internal\nre:\\bbox-[0-9]+\\b\nAcmeCustomer\n", encoding="utf-8")
        extra.write_text("ExtraName\nAcmeCustomer\n", encoding="utf-8")
        names = internal_names([deny, extra, Path(td) / "missing.txt"])
        checks = [
            (names == [r"re:\bbox-[0-9]+\b", "AcmeCustomer", "ExtraName"], "lists merged"),
            (any(f[1] == "internal name" for f in scan("runs on box-12", names=names)), "deny list regex"),
            (any(f[1] == "internal name" for f in scan("for ExtraName", names=names)), "extra list"),
            (not any(f[1] == "internal name" for f in scan("nothing internal", names=names)), "quiet"),
            (DENYLIST.name == "public_check_denylist.txt", "default path is the shared deny list"),
            (any(f[1] == "internal name" for f in scan("signed: Firma GmbH. Thanks", names=["Firma GmbH."])),
             "name ending in punctuation"),
            (not any(f[1] == "internal name" for f in scan("FirmaGmbHX", names=["Firma"])), "no match inside a word"),
        ]
        for bad_allow in ("Musterfirma", {"a": 1}, ["ok", 3]):
            try:
                scan("text", bad_allow, names=[])
                checks.append((False, f"leak_allow {type(bad_allow).__name__} rejected"))
            except DisclosureError:
                checks.append((True, f"leak_allow {type(bad_allow).__name__} rejected"))
        this = sys.modules[__name__]
        saved = this.DENYLIST
        try:
            this.DENYLIST = Path(td) / "no-deny-list.txt"
            try:
                internal_names()
                checks.append((False, "missing deny list fails closed"))
            except DisclosureError:
                checks.append((True, "missing deny list fails closed"))
        finally:
            this.DENYLIST = saved
        for ok, label in checks:
            total += 1
            if not ok:
                bad += 1
                out(f"ERROR: self-test deny list: {label}")
    out(f"leak_scan self-test: {total - bad}/{total} OK")
    return 1 if bad else 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Check disclosure text for leaks")
    ap.add_argument("draft", nargs="?")
    ap.add_argument("--text", help="any text file instead of a draft")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args(argv)
    try:
        if a.self_test:
            return self_test()
        if a.text:
            return report(scan(Path(a.text).read_text(encoding="utf-8")))
        if not a.draft:
            ap.error("give a draft or --text")
        meta, text, _ = read_draft(Path(a.draft))
        head = "\n".join(str(meta.get(k, "")) for k in ("title", "summary", "subject"))
        return report(scan(head + "\n" + text, meta.get("leak_allow", [])))
    except DisclosureError as exc:
        err(f"ERROR: {exc}")
        return 2


if __name__ == "__main__":
    sys.exit(main())
