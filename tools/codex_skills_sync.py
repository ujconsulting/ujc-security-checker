#!/usr/bin/env python3
"""Mirrors the project skills from .claude/skills/ to .agents/skills/ for Codex.

Codex CLI (measured with 0.156.0) finds project skills under <repo>/.agents/skills/<name>/SKILL.md;
~/.codex/skills is only the location for the user's own skills. The source stays
.claude/skills/ - the mirror carries name and description and points to the full text,
plus a translation of the Claude tool names. Single source, no copying by hand.
Skills that git ignores (local-only skills of the operator) are mirrored as well, but a
difference in their mirror does not count in --check - they are never published.

    python tools/codex_skills_sync.py             # write the mirror
    python tools/codex_skills_sync.py --check     # check only, exit 1 on deviation
    python tools/codex_skills_sync.py --self-test

Exit: 0 identical or written, 1 deviation (--check), 2 error.
Output is ASCII only.
"""
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ".claude/skills"
TARGET = ".agents/skills"
MARKER = "<!-- generated by tools/codex_skills_sync.py - do not edit by hand -->"
# Agent Skills limit for the description; longer ones are cut at the end of a sentence
MAX_DESC = 1024

TRANSLATION = """\
## Reading this under Codex

The instructions are written for Claude Code. Under Codex:

- Tool names are actions: `Read`/`Grep`/`Glob` = read a file or `rg`, `Edit`/`Write` =
  change a file, `Bash`/`PowerShell` = shell. `Agent`/sub-agent = do it yourself, one after another.
- A reference to another skill (`Skill <name>`) means: read `{target}/<name>/SKILL.md`;
  global Claude skills live under `~/.claude/skills/<name>/SKILL.md`.
- Hooks and the guard do not run under Codex. Their rules still apply and are written in
  `AGENTS.md` (no push to GitHub without being told, no `git add -A`, approvals before any
  external effect).
- Run all commands from the repository root.
"""


def frontmatter(text):
    m = re.match(r"^---\r?\n(.*?)\r?\n---\r?\n", text, re.S)
    if not m:
        return None
    fields = {}
    for line in m.group(1).splitlines():
        k, sep, v = line.partition(":")
        if sep and k.strip() in ("name", "description"):
            fields[k.strip()] = v.strip()
    return fields


def shorten(desc):
    if len(desc) <= MAX_DESC:
        return desc
    part = desc[: MAX_DESC - 40]
    cut = max(part.rfind(". "), part.rfind(", ("))
    part = part[: cut + 1] if cut > 200 else part
    return part.rstrip() + " (shortened, full text in the skill)"


def mirror_text(name, desc, source_rel):
    # YAML double-quoted scalar: drop control characters, escape the backslash first, then the quote
    desc = "".join(ch for ch in shorten(desc) if ch >= " " and ch != "\x7f")
    desc = desc.replace("\\", "\\\\").replace('"', '\\"')
    return (
        f"---\nname: {name}\ndescription: \"{desc}\"\n---\n{MARKER}\n\n"
        f"# {name} (Codex mirror)\n\n"
        f"Read the complete skill `{source_rel}` first and follow it. "
        f"This file is only the entry point so that Codex finds the skill.\n\n"
        + TRANSLATION.format(target=TARGET)
    )


def desired_state(root):
    desired, errors = {}, []
    for f in sorted((root / SOURCE).glob("*/SKILL.md")):
        fm = frontmatter(f.read_text(encoding="utf-8"))
        if not fm or "name" not in fm or "description" not in fm:
            errors.append(f"ERROR: {f.relative_to(root).as_posix()} without name/description")
            continue
        if fm["name"] != f.parent.name:
            errors.append(f"ERROR: {f.parent.name}: name '{fm['name']}' does not match the folder")
            continue
        rel = f.relative_to(root).as_posix()
        desired[f"{TARGET}/{fm['name']}/SKILL.md"] = mirror_text(fm["name"], fm["description"], rel)
    return desired, errors


def ignored_paths(root, paths):
    """Paths that git ignores (local-only skills). Without git or outside a repository:
    none - then every skill counts."""
    if not paths:
        return set()
    try:
        res = subprocess.run(["git", "-C", str(root), "check-ignore", "--no-index", "--stdin", "-z"],
                             input="\0".join(paths).encode("utf-8"), stdout=subprocess.PIPE,
                             stderr=subprocess.DEVNULL, check=False)
    except OSError:
        return set()
    if res.returncode not in (0, 1):
        return set()
    return {p for p in res.stdout.decode("utf-8", "replace").split("\0") if p}


def is_generated(text):
    """True only if the file starts with the exact generated header (front matter, then marker)."""
    lines = text.replace("\r\n", "\n").split("\n")
    if len(lines) < 5 or lines[0] != "---":
        return False
    try:
        end = lines.index("---", 1)
    except ValueError:
        return False
    return end <= 4 and len(lines) > end + 1 and lines[end + 1] == MARKER


def sync(root, write):
    desired, errors = desired_state(root)
    for line in errors:
        print(line)
    existing = [p.relative_to(root).as_posix()
                for p in sorted((root / TARGET).glob("*/SKILL.md"))] if (root / TARGET).exists() else []
    # A skill that git ignores stays local: its mirror is still written, but in --check a
    # difference there does not count (it is never published).
    local_only = ignored_paths(root, sorted(set(desired) | set(existing)
                                            | {f"{SOURCE}/{r.split('/')[2]}/SKILL.md" for r in desired}))

    def is_local(rel):
        name = rel.split("/")[2]
        return rel in local_only or f"{SOURCE}/{name}/SKILL.md" in local_only

    deviations = 0
    for rel, text in desired.items():
        p = root / rel
        current = p.read_text(encoding="utf-8") if p.exists() else None
        if current == text:
            continue
        if is_local(rel):
            print(f"LOCAL ONLY (ignored by git, not counted): {rel}")
        else:
            deviations += 1
            print(f"{'NEW' if current is None else 'CHANGED'}: {rel}")
        if write:
            p.parent.mkdir(parents=True, exist_ok=True)
            with open(p, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
    for rel in existing:
        p = root / rel
        if rel in desired:
            continue
        if not is_generated(p.read_text(encoding="utf-8")):
            print(f"UNEXPECTED FILE, not deleted: {rel} (no generated header, source missing)")
            continue
        if is_local(rel):
            print(f"LOCAL ONLY (ignored by git, not counted): {rel} (source missing)")
            continue
        deviations += 1
        print(f"ORPHANED: {rel} (source missing)")
        if write:
            p.unlink()
            if not any(p.parent.iterdir()):
                p.parent.rmdir()
    print(f"OK: {len(desired)} skills, {deviations} deviations" + (" fixed" if write and deviations else ""))
    if errors:
        return 2
    return 1 if (deviations and not write) else 0


def self_test():
    with tempfile.TemporaryDirectory() as t:
        r = pathlib.Path(t)
        (r / SOURCE / "probe").mkdir(parents=True)
        (r / SOURCE / "probe" / "SKILL.md").write_text(
            "---\nname: probe\ndescription: " + "Sentence one. " * 150 + "\n---\n# x\n", encoding="utf-8")
        assert sync(r, False) == 1
        assert sync(r, True) == 0
        assert sync(r, False) == 0
        txt = (r / TARGET / "probe" / "SKILL.md").read_text(encoding="utf-8")
        assert len(frontmatter(txt)["description"]) <= MAX_DESC + 2
        (r / SOURCE / "probe" / "SKILL.md").unlink()
        (r / SOURCE / "probe").rmdir()
        assert sync(r, False) == 1
        assert sync(r, True) == 0
        assert not (r / TARGET / "probe").exists()
        # a file that merely mentions the marker is not ours: left alone, reported
        (r / TARGET / "hand").mkdir(parents=True)
        (r / TARGET / "hand" / "SKILL.md").write_text(
            "---\nname: hand\n---\nNotes that quote " + MARKER + " somewhere.\n", encoding="utf-8")
        assert sync(r, False) == 0
        assert sync(r, True) == 0
        assert (r / TARGET / "hand" / "SKILL.md").exists()
        shutil.rmtree(r / TARGET / "hand")
        # backslashes and quotes in the description are escaped for the YAML scalar
        (r / SOURCE / "esc").mkdir(parents=True)
        (r / SOURCE / "esc" / "SKILL.md").write_text(
            "---\nname: esc\ndescription: Run C:\\tools\\x and say \"hi\"\n---\n# x\n", encoding="utf-8")  # public-check: allow internal
        assert sync(r, True) == 0
        line = [z for z in (r / TARGET / "esc" / "SKILL.md").read_text(encoding="utf-8").splitlines()
                if z.startswith("description:")][0]
        assert line == 'description: "Run C:\\\\tools\\\\x and say \\"hi\\""', line  # public-check: allow internal
        shutil.rmtree(r / SOURCE / "esc")
        shutil.rmtree(r / TARGET / "esc")
        # ignored (local-only) skills: mirror written, never counted in --check
        if shutil.which("git"):
            subprocess.run(["git", "-C", str(r), "init", "-q"], check=True)
            (r / ".gitignore").write_text("/.claude/skills/local/\n/.agents/skills/local/\n",
                                          encoding="utf-8")
            (r / SOURCE / "local").mkdir(parents=True)
            (r / SOURCE / "local" / "SKILL.md").write_text(
                "---\nname: local\ndescription: Local only.\n---\n# x\n", encoding="utf-8")
            assert sync(r, False) == 0
            assert sync(r, True) == 0
            assert (r / TARGET / "local" / "SKILL.md").exists()
            (r / TARGET / "local" / "SKILL.md").write_text(MARKER + "\nstale\n", encoding="utf-8")
            assert sync(r, False) == 0
            (r / SOURCE / "public").mkdir(parents=True)
            (r / SOURCE / "public" / "SKILL.md").write_text(
                "---\nname: public\ndescription: Public.\n---\n# x\n", encoding="utf-8")
            assert sync(r, False) == 1
    print("SELF-TEST OK")
    return 0


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        sys.exit(self_test())
    sys.exit(sync(ROOT, "--check" not in sys.argv))
